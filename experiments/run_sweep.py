MAX_CAPTURE_DIR_BYTES = 2 * 1024 * 1024 * 1024  # 2 GB limit

def get_dir_size_bytes(dir_path: str) -> int:
    if not os.path.exists(dir_path):
        return 0
    total = 0
    for root, _, files in os.walk(dir_path):
        for f in files:
            fp = os.path.join(root, f)
            if not os.path.islink(fp):
                total += os.path.getsize(fp)
    return total

def get_dir_size_str(dir_path: str) -> str:
    size = get_dir_size_bytes(dir_path)
    for unit in ['B', 'KB', 'MB', 'GB', 'TB']:
        if size < 1024.0:
            return f"{size:.2f} {unit}"
        size /= 1024.0
    return f"{size:.2f} PB"

def check_disk_limit_exceeded(dir_path: str, max_bytes: int = MAX_CAPTURE_DIR_BYTES) -> bool:
    size = get_dir_size_bytes(dir_path)
    return size > max_bytes

def clear_captured_kv_dir(dir_path: str):
    if os.path.exists(dir_path):
        shutil.rmtree(dir_path)
    os.makedirs(dir_path, exist_ok=True)

def compute_text_similarity(s1: str, s2: str) -> float:
    if not s1 and not s2:
        return 1.0
    if not s1 or not s2:
        return 0.0
    return round(difflib.SequenceMatcher(None, s1.strip(), s2.strip()).ratio(), 4)

def parse_args():
    parser = argparse.ArgumentParser(description="Run KV-cache tamper experiment sweep")
    parser.add_argument("--max_samples", type=int, default=30, help="Number of GSM8K examples")
    parser.add_argument("--model_name", type=str, default="Qwen/Qwen3-0.6B", help="Model name")
    parser.add_argument("--task", type=str, default="gsm8k", help="Task name")
    parser.add_argument("--prompt", type=str, default="sequential", help="Prompt structure")
    parser.add_argument("--think", action="store_true", default=False, help="Add think token")
    parser.add_argument("--device", type=str, default="cuda", help="Execution device (cuda/mps/cpu)")
    parser.add_argument("--latent_steps", type=int, default=0, help="Number of latent steps")
    parser.add_argument("--max_new_tokens", type=int, default=512, help="Max tokens generated by Judger")
    parser.add_argument("--seed", type=int, default=42, help="Random seed")
    parser.add_argument("--results_csv", type=str, default=os.path.join(ROOT_DIR, "results", "sweep_results.csv"))
    parser.add_argument("--captured_dir", type=str, default=os.path.join(ROOT_DIR, "logs", "captured_kv"))
    parser.add_argument("--stats_csv", type=str, default=os.path.join(ROOT_DIR, "logs", "kv_handoff_stats.csv"))
    parser.add_argument("--clear_captures", action="store_true", default=True, help="Wipe captured_kv before starting")
    parser.add_argument("--no_clear_captures", dest="clear_captures", action="store_false")
    return parser.parse_args()

def main():
    args = parse_args()
    set_seed(args.seed)
    device = auto_device(args.device)

    print("==================================================")
    print("        KV-CACHE ATTACK EXPERIMENT SWEEP          ")
    print("==================================================")
    print(f"Model: {args.model_name} | Device: {device}")
    print(f"Samples: {args.max_samples} GSM8K problems")
    print(f"Decoding: Greedy (temperature=0.0)")

    # 1. Disk management check before run
    print(f"\n[Disk Check] logs/captured_kv size before sweep: {get_dir_size_str(args.captured_dir)}")
    if args.clear_captures:
        print("[Disk Management] --clear_captures is active: clearing logs/captured_kv...")
        clear_captured_kv_dir(args.captured_dir)
        print(f"[Disk Check] logs/captured_kv size after clear: {get_dir_size_str(args.captured_dir)}")

    # Load dataset
    print(f"\n[Data] Loading {args.max_samples} GSM8K test examples...")
    dataset_iter = load_gsm8k(split="test")
    dataset_samples = []
    for idx, item in enumerate(dataset_iter):
        if idx >= args.max_samples:
            break
        item["request_id"] = idx
        dataset_samples.append(item)
    print(f"[Data] Loaded {len(dataset_samples)} samples.")

    # Initialize model
    print("\n[Model] Loading model and tokenizer...")
    model = ModelWrapper(args.model_name, device, use_vllm=False, args=args)
    print("[Model] Model loaded successfully.")

    # Define sweep combos:
    # Combo format: dict with tamper_type, carrier, layer_range, strength
    combos = [
        {"tamper_type": "clean", "carrier": "none", "layer_range": "all", "strength": 0.0},
        {"tamper_type": "noise", "carrier": "K", "layer_range": "all", "strength": 0.1},
        {"tamper_type": "noise", "carrier": "K", "layer_range": "all", "strength": 0.5},
        {"tamper_type": "noise", "carrier": "K", "layer_range": "all", "strength": 1.5},
    ]

    os.makedirs(os.path.dirname(os.path.abspath(args.results_csv)), exist_ok=True)
    csv_headers = [
        "example_idx",
        "question",
        "gold",
        "combo_id",
        "tamper_type",
        "carrier",
        "layer_range",
        "strength",
        "prediction",
        "correct",
        "clean_prediction",
        "clean_correct",
        "text_similarity_vs_clean",
        "time_sec",
    ]

    results_rows = []

    # Store clean baseline outputs per example_idx to compute text similarity
    clean_baselines: Dict[int, Dict[str, Any]] = {}

    for combo_idx, combo in enumerate(combos):
        t_type = combo["tamper_type"]
        carrier = combo["carrier"]
        l_range = combo["layer_range"]
        strength = combo["strength"]
        combo_str = f"[{combo_idx+1}/{len(combos)}] {t_type.upper()} | carrier={carrier} | layers={l_range} | strength={strength}"
        print(f"\n--------------------------------------------------")
        print(f"Running Combo {combo_str}")
        print(f"--------------------------------------------------")

        # Check disk space limit
        if check_disk_limit_exceeded(args.captured_dir):
            print(f"\n[WARNING] logs/captured_kv/ exceeded 2GB limit! Current size: {get_dir_size_str(args.captured_dir)}")
            print("[STOPPING] Halting sweep to protect disk space.")
            break

        # Only enable raw capture if tamper_type == "swap"
        capture_raw = (t_type == "swap")

        # Build TamperHook if not clean
        tamper_hook = None
        if t_type != "clean":
            tamper_hook = TamperHook(
                tamper_type=t_type,
                carrier=carrier,
                layer_range=None if l_range == "all" else l_range,
                strength=strength,
                target_handoff=("Refiner", "Judger"),
            )

        # Build KVHookManager
        kv_hook = KVHookManager(
            log_csv_path=None,  # skip handoff CSV overhead during sweep runs
            capture_raw=capture_raw,
            capture_dir=args.captured_dir,
            tamper_fn=tamper_hook,
        )

        method = LatentMASMethod(
            model,
            latent_steps=args.latent_steps,
            judger_max_new_tokens=args.max_new_tokens,
            temperature=0.0,  # greedy decoding for deterministic comparison
            top_p=0.95,
            generate_bs=1,
            args=args,
            kv_hook=kv_hook,
        )

        correct_count = 0
        total_time = 0.0

        for item in tqdm(dataset_samples, desc=f"Combo {t_type} (s={strength})"):
            req_id = item["request_id"]
            start_t = time.time()
            res = method.run_item(item)
            elapsed = time.time() - start_t
            total_time += elapsed

            pred = res.get("prediction")
            gold = res.get("gold")
            correct = res.get("correct", False)
            if correct:
                correct_count += 1

            if t_type == "clean":
                clean_baselines[req_id] = {
                    "prediction": pred,
                    "raw_prediction": res.get("raw_prediction", ""),
                    "correct": correct,
                }
                clean_pred = pred
                clean_ok = correct
                similarity = 1.0
            else:
                clean_info = clean_baselines.get(req_id, {})
                clean_pred = clean_info.get("prediction", "")
                clean_ok = clean_info.get("correct", False)
                similarity = compute_text_similarity(
                    clean_info.get("raw_prediction", ""),
                    res.get("raw_prediction", "")
                )

            row = {
                "example_idx": req_id,
                "question": item["question"].replace("\n", " ").strip()[:100],
                "gold": gold,
                "combo_id": combo_idx,
                "tamper_type": t_type,
                "carrier": carrier,
                "layer_range": str(l_range),
                "strength": strength,
                "prediction": pred,
                "correct": correct,
                "clean_prediction": clean_pred,
                "clean_correct": clean_ok,
                "text_similarity_vs_clean": similarity,
                "time_sec": round(elapsed, 3),
            }
            results_rows.append(row)

            # Disk cleanup if swap loaded any donor files
            if t_type == "swap":
                # delete donor file after extraction as required
                donor_file = getattr(tamper_hook, "donor_kv_path", None)
                if donor_file and os.path.exists(donor_file):
                    os.remove(donor_file)

        acc = (correct_count / len(dataset_samples)) * 100.0
        print(f"Summary for Combo: Accuracy = {acc:.1f}% ({correct_count}/{len(dataset_samples)}) | Time: {total_time:.1f}s")

    # Save to results CSV
    print(f"\n[Saving] Writing full sweep results to {args.results_csv}...")
    with open(args.results_csv, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=csv_headers)
        writer.writeheader()
        writer.writerows(results_rows)
    print(f"[Saving] Saved {len(results_rows)} rows to results CSV.")

    # Final disk check
    final_cap_size = get_dir_size_str(args.captured_dir)
    print(f"\n[Disk Check] Final size of logs/captured_kv/: {final_cap_size}")

    # Print summary table
    print("\n==================================================")
    print("              SWEEP SUMMARY RESULTS               ")
    print("==================================================")
    print(f"{'Combo':<10} {'Tamper':<8} {'Carrier':<8} {'Strength':<10} {'Accuracy':<10} {'Avg Sim vs Clean':<18}")
    print("-" * 68)

    for combo_idx, combo in enumerate(combos):
        t_type = combo["tamper_type"]
        carrier = combo["carrier"]
        strength = combo["strength"]
        matching_rows = [r for r in results_rows if r["combo_id"] == combo_idx]
        if not matching_rows:
            continue
        acc = sum(1 for r in matching_rows if r["correct"]) / len(matching_rows) * 100.0
        avg_sim = sum(r["text_similarity_vs_clean"] for r in matching_rows) / len(matching_rows)
        print(f"{combo_idx:<10} {t_type:<8} {carrier:<8} {strength:<10} {acc:>5.1f}%     {avg_sim:>12.3f}")
    print("==================================================")

if __name__ == "__main__":
    main()
